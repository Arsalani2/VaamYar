package com.example.util

/**
 * فیکس bug.md/P3-1: هویت افراد در وام‌یار «نام‌پایه» است (طبق تصمیم A4 در bug.md ستون
 * userId به DebtorShare اضافه نمی‌شود). پس «نام» باید مثل یک کلید رفتار کند؛ مقایسهٔ خام
 * رشته‌ای با کوچک‌ترین تفاوتِ تایپی می‌شکند: کیبورد عربی‌نویس «ي» و «ك» تولید می‌کند،
 * فاصلهٔ تکراری یا نیم‌فاصله در مقایسه با فاصله فرق می‌افتد و نتیجه: سهم شریک صفر حساب
 * می‌شود، حذفِ کاربرِ دارایِ سهم مجاز می‌شود یا تغییرِ نام، سهم‌ها را از صاحبشان جدا می‌کند.
 *
 * این آبجکت قاعدهٔ واحدِ تطبیق نام در کل اپ است:
 *  - [canonicalName]: شکل استاندارد برای «ذخیره» در دیتابیس؛
 *  - [matchKey] و [namesMatch]: تطبیقِ داده‌های قدیمی — هر شکل تایپی که دارند — با هم.
 *
 * محدودیتِ پذیرفته‌شدهٔ A4 همچنان پابرجاست: دو نفرِ واقعاً هم‌نام با تطبیق نام‌پایه قابل
 * تفکیک نیستند.
 */
object PersianNameNormalizer {

    private const val ZWNJ = '\u200C' // نیم‌فاصله

    /**
     * شکل استاندارد نام برای ذخیره‌سازی: بدون فاصله‌های ابتدا/انتها و فاصله‌های تکراری، و با
     * حروف فارسی به‌جای هم‌ارزهای عربی (ي → ی، ك → ک، ة → ه) که کیبوردهای عربی‌نویس تولید
     * می‌کنند. چون نمایش نام هم از همین فرم می‌آید، نام‌ها همیشه یکدست دیده می‌شوند.
     */
    fun canonicalName(name: String): String = name.trim()
        .replace('ي', 'ی')
        .replace('ك', 'ک')
        .replace('ة', 'ه')
        .replace(Regex("\\s+"), " ")

    /**
     * کلید مقایسه برای تطبیق هویت: علاوه بر استانداردسازیِ [canonicalName]، نیم‌فاصله هم مثل
     * فاصله رفتار می‌شود («محمد‌رضا» و «محمد رضا» یک نفرند). همهٔ مقایسه‌های نام‌پایه در
     * ریپازیتوری و ViewModel باید از این کلید عبور کنند تا داده‌های ثبت‌شدهٔ قدیمی — که
     * پیش از این فیکس ذخیره شده‌اند — هم درست مچ شوند.
     */
    fun matchKey(name: String): String =
        canonicalName(name).replace(ZWNJ, ' ').replace(Regex("\\s+"), " ")

    /** تطبیق دو نام با کلید استاندارد. */
    fun namesMatch(a: String, b: String): Boolean = matchKey(a) == matchKey(b)
}
